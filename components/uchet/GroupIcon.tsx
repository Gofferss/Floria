export type GroupIconKey = keyof typeof GROUP_ICONS;

export const GROUP_ICON_KEYS = Object.keys(GROUP_ICONS) as GroupIconKey[];

export function isGroupIconKey(value: unknown): value is GroupIconKey {
  return typeof value === "string" && value in GROUP_ICONS;
}

export function GroupIcon({ icon, className = "h-6 w-6" }: { icon: string | null | undefined; className?: string }) {
  const def = GROUP_ICONS[isGroupIconKey(icon) ? icon : "other"];
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.6}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      className={className}
    >
      {def.paths.map((d) => (
        <path key={d} d={d} />
      ))}
    </svg>
  );
}

// Значок новой группы — по названию, потом по виду. Тот же порядок, что
// в миграции 028: «кустовая роза» раньше «розы», иначе обе стали бы розой.
const GUESS_BY_TITLE: [string, GroupIconKey][] = [
  ["кустов", "spray"],
  ["роз", "rose"],
  ["хризант", "chrys"],
  ["горш", "pot"],
  ["игруш", "bear"],
  ["искусств", "artificial"],
  ["сухоцв", "dried"],
  ["упаков", "wrap"],
  ["услуг", "scissors"],
  ["уценк", "sale"],
  ["открыт", "card"],
  ["шар", "balloon"],
  ["букет", "bouquet"],
  ["зелен", "leaf"],
  ["подар", "gift"],
];

const GUESS_BY_KIND: Record<string, GroupIconKey> = {
  flower: "tulip",
  greenery: "leaf",
  decor: "dried",
  packaging: "wrap",
  gift: "gift",
  print: "card",
  service: "scissors",
  bouquet: "bouquet",
};

export function guessGroupIcon(title: string, kind: string): GroupIconKey {
  const t = title.toLowerCase();
  const hit = GUESS_BY_TITLE.find(([word]) => t.includes(word));
  if (hit) return hit[1];
  if (t.startsWith("дом")) return "home";
  return GUESS_BY_KIND[kind] ?? "other";
}
