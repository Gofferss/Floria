-- ================================================================
-- Несколько фотографий собранного заказа вместо одной.
--
-- Зачем. В заказе может быть два, три, пять букетов — их собирают
-- и везут вместе. Поле было одно (assembled_photo_url), поэтому
-- флорист мог показать клиенту только один букет из нескольких, а
-- за остальные клиент платил вслепую. Ровно тот страх, ради которого
-- фото и затевалось: «пришлют не то».
--
-- Старую колонку НЕ удаляем. Её содержимое переносим в массив, но сама
-- она остаётся как страховка на время выкатки: если приложение и
-- миграция разъедутся во времени, админка не должна упасть на
-- несуществующей колонке. Удалить её можно отдельной миграцией, когда
-- новый код отработает.
-- ================================================================

begin;

alter table orders
  add column if not exists assembled_photos text[] not null default '{}';

comment on column orders.assembled_photos is
  'Фотографии собранного заказа — по одной на букет. Флорист загружает в админке, клиент получает их альбомом в боте.';

-- Переносим то, что уже снято. idempotent: повторный запуск ничего не
-- задвоит, потому что берём только пустые массивы.
update orders
   set assembled_photos = array[assembled_photo_url]
 where assembled_photo_url is not null
   and assembled_photo_url <> ''
   and cardinality(assembled_photos) = 0;

comment on column orders.assembled_photo_url is
  'УСТАРЕЛО: заменено на assembled_photos (массив). Оставлено как копия на время выкатки, кодом не используется.';

-- Отметка об отправке теперь относится ко всему набору: добавили или
-- убрали снимок — набор стал другим, и клиент его ещё не видел.
comment on column orders.assembled_photo_sent_at is
  'Когда клиенту ушёл текущий набор фотографий. Любое изменение набора обнуляет отметку.';

commit;
