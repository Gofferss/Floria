-- ================================================================
-- Онлайн-оплата через ВТБ (СБП).
--
-- Зачем отдельные поля, если payment_status уже есть. Статус отвечает на
-- вопрос «оплачено ли», а эти поля — на вопрос «чем человеку доплатить,
-- если он закрыл вкладку». Ссылка на оплату живёт ограниченное время, и
-- без неё недооплаченный заказ превращается в тупик: деньги не пришли,
-- а повторить попытку неоткуда.
--
-- payment_provider_id уже существует — в нём храним orderCode, внешний
-- идентификатор ордера на стороне ВТБ.
--
-- Про сверку. Уведомления шлюза не подписаны и вдобавок могут просто не
-- дойти. Поэтому заказы в статусе pending периодически перепроверяются
-- запросом к ВТБ (app/api/payments/reconcile) — частичный индекс ниже
-- ровно для этой выборки.
-- ================================================================

alter table orders
  add column if not exists payment_url text,
  add column if not exists payment_expires_at timestamptz,
  -- Когда последний раз спрашивали у шлюза, что с этим платежом.
  add column if not exists payment_checked_at timestamptz,
  -- Готовый текст для флориста: состав, адрес, открытка, комментарий курьеру.
  -- Складывается при оформлении, а отправляется после оплаты — собирать его
  -- заново пришлось бы из пяти таблиц, причём в момент, когда важна скорость.
  add column if not exists staff_notify_details text;

comment on column orders.payment_url is
  'Ссылка на оплату (СБП/форма ВТБ). Нужна, чтобы клиент мог вернуться и доплатить.';

comment on column orders.payment_expires_at is
  'Когда ссылка на оплату перестанет работать. После этого нужна новая.';

comment on column orders.payment_checked_at is
  'Когда мы в последний раз сами спрашивали у ВТБ статус платежа (сверка).';

-- Выборка для сверки: незакрытые платежи, самые давно не проверенные первыми.
create index if not exists orders_payment_pending_idx
  on orders (payment_checked_at nulls first, created_at)
  where payment_status = 'pending';
