-- ================================================================
-- Состояние фоновых задач.
--
-- Проект дважды напоролся на одно и то же: вход по СМС был сломан месяц
-- (адрес хука указывал в никуда), а планировщик напоминаний не был
-- подключён вообще — годовые напоминания не отправлялись ни разу. Оба
-- случая нашлись случайно, при разборе других задач. Логи писались
-- исправно, но логи никто не читает, пока не заподозрит неладное.
--
-- Отсюда правило: задача, работающая без человека, обязана уметь позвать
-- человека, когда перестала работать. Таблица хранит ровно то, что нужно,
-- чтобы не спамить: сколько сбоев подряд и когда в последний раз писали.
-- ================================================================

create table if not exists health_checks (
  key                   text primary key,
  consecutive_failures  int not null default 0,
  last_error            text,
  alerted_at            timestamptz,
  last_ok_at            timestamptz,
  updated_at            timestamptz not null default now()
);

-- Служебная таблица: читает и пишет только сервер через service-role.
-- RLS без политик = доступ закрыт для anon и authenticated.
alter table health_checks enable row level security;

comment on table health_checks is
  'Состояние фоновых задач — чтобы молчаливый сбой не оставался незамеченным.';
comment on column health_checks.consecutive_failures is
  'Сколько прогонов подряд закончились ошибкой. Обнуляется при первом успешном.';
comment on column health_checks.alerted_at is
  'Когда в последний раз написали в Telegram. Не даёт слать одно и то же каждый прогон.';
