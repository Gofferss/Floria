-- ================================================================
-- Ответ на просьбу об отзыве должен куда-то попадать.
--
-- Бот через сутки после доставки писал: «Если что-то не так — просто
-- ответьте на это сообщение, разберёмся». Человек отвечал — и его текст
-- не подходил ни под одну команду, ни под один сценарий диалога, после
-- чего срабатывала ветка «idle + произвольный текст»: бот показывал
-- меню со словами «Выберите действие:». Написанное не сохранялось и
-- никому не отправлялось.
--
-- Это было хуже потерянной заявки из формы: там сообщение терялось
-- из-за сбоя, здесь мы САМИ звали написать и выбрасывали ответ. Причём
-- ровно у тех, кто остался недоволен, — у людей, которых мы намеренно
-- увели от публичного отзыва обещанием разобраться.
--
-- Складываем такие ответы в contact_requests: это ровно то же самое —
-- сообщение клиента, которое обязан увидеть человек. Заводить вторую
-- таблицу с той же механикой (добор, контроль здоровья, раздел в
-- админке) незачем, нужно лишь различать источник.
-- ================================================================

alter table contact_requests
  add column if not exists source text not null default 'form',
  add column if not exists order_id uuid references orders(id) on delete set null;

comment on column contact_requests.source is
  'Откуда обращение: form — форма на сайте, bot_review — ответ на просьбу об отзыве в боте.';

comment on column contact_requests.order_id is
  'Заказ, о котором речь (для ответов на просьбу об отзыве). null для обращений с сайта.';

-- Ответы недовольных клиентов важнее прочего: по ним нужно связаться
-- быстро, пока человек не ушёл писать публичный отзыв.
create index if not exists contact_requests_source_idx
  on contact_requests (source, created_at desc)
  where handled_at is null;
