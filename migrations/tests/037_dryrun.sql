-- Прогон 037_anonymous_sender.sql вместе с тестом в одной транзакции, с откатом.
-- Проверяет миграцию на боевой базе до того, как её применить. Сгенерирован scratch-скриптом.
begin;
-- ================================================================
-- 037. Анонимный букет: «не указывать отправителя».
--
-- На странице доставки давно написано «открытку можно оставить
-- анонимной», а в оформлении заказа выбрать это было негде — человек мог
-- только дописать просьбу в комментарий курьеру, и флорист её легко
-- пропускал. Теперь это галочка в оформлении, и её видят все, кто
-- собирает и везёт: сообщение сотрудникам, админка, «Заказы» и маршрут
-- курьера в Учёте, заметка в Posiflora.
--
-- Только для букета другому человеку: себе анонимно не дарят — сервер
-- сбрасывает признак, если получатель — сам заказчик.
-- ================================================================


alter table orders add column if not exists is_anonymous boolean not null default false;

comment on column orders.is_anonymous is
  'Не называть получателю отправителя: открытку не подписывать, курьер не говорит, от кого букет';


-- ================================================================
-- Проверка миграции 037 (анонимный букет). Откатывается.
-- ================================================================



do $$
begin
  -- 1. Признак есть, по умолчанию выключен — старые заказы не стали анонимными.
  if exists (select 1 from orders where is_anonymous) then
    raise exception 'ТЕСТ 1: после миграции есть анонимные заказы';
  end if;
  if (select column_default from information_schema.columns
       where table_schema = 'public' and table_name = 'orders' and column_name = 'is_anonymous') <> 'false' then
    raise exception 'ТЕСТ 1: умолчание не false';
  end if;
  raise notice 'OK 1: признак есть, у прежних заказов выключен';

  -- 2. Аноним не пишет в заказы и после новой колонки (миграция 035).
  if has_table_privilege('anon', 'public.orders', 'INSERT') or has_table_privilege('anon', 'public.orders', 'UPDATE') then
    raise exception 'ТЕСТ 2: у anon появилась запись в orders';
  end if;
  raise notice 'OK 2: запись в заказы анониму по-прежнему закрыта';

  raise notice '037: все 2 проверки прошли';
end $$;


rollback;
