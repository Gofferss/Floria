-- ================================================================
-- Закрываем возможность клиенту переписать себе баланс бонусов.
--
-- Что было. Supabase по умолчанию выдаёт ролям anon и authenticated
-- права INSERT/UPDATE/DELETE на все таблицы, а единственной защитой
-- остаётся RLS. На customers политика разрешала обновлять СВОЮ строку:
--
--   UPDATE ... USING (auth_user_id = auth.uid())
--
-- RLS работает на уровне строк, а не колонок, поэтому вошедший клиент
-- мог изменить у себя ЛЮБОЕ поле — включая bonus_balance,
-- posiflora_client_id и is_blocked.
--
-- Чем это грозило. В app/api/orders/route.ts живой баланс запрашивается
-- у Posiflora, но только если у клиента заполнен posiflora_client_id;
-- иначе берётся значение из БД. Отсюда рабочая связка: обнулить у себя
-- posiflora_client_id, выставить bonus_balance побольше — и оформить
-- заказ, списав несуществующие бонусы в ноль. То есть бесплатный букет.
--
-- Почему снимаем права целиком, а не по колонкам. Клиентский код НИКОГДА
-- не пишет в customers напрямую: в браузерных и серверных компонентах
-- только SELECT, а все изменения идут через service-role (lib/actions/*,
-- lib/customer-sync.ts), которому RLS и гранты не писаны. Значит право
-- записи для anon/authenticated не нужно ни одному сценарию, и его
-- отсутствие ничего не ломает. Список разрешённых колонок пришлось бы
-- поддерживать вручную при каждой миграции — а забытая колонка снова
-- открыла бы дыру.
--
-- SELECT не трогаем: на нём держится чтение своей карточки в кабинете
-- и баланс в шапке.
-- ================================================================

revoke insert, update, delete on public.customers from anon;
revoke insert, update, delete on public.customers from authenticated;

-- Политики больше не на что опереться — убираем, чтобы не создавать
-- ложного впечатления, что запись разрешена.
drop policy if exists customer_update_own on public.customers;
drop policy if exists customers_update_own on public.customers;
