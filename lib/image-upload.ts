// ================================================================
// Какие картинки принимаем на загрузку — общий список для всех форм.
//
// Раньше каждая загрузка проверяла только «тип начинается с image/», а
// расширение файла брала из его имени. Под это подходил SVG — а SVG
// это не картинка, а документ, внутри которого может быть скрипт: по
// публичной ссылке хранилища он бы исполнился в браузере. И имя вроде
// «фото.html» с подписанным типом image/png ложилось в хранилище как
// .html. Теперь пускаем только растровые форматы камер и браузеров, а
// расширение выводим из типа, а не из имени.
// ================================================================

const IMAGE_EXTENSIONS: Record<string, string> = {
  "image/jpeg": "jpg",
  "image/png": "png",
  "image/webp": "webp",
  "image/gif": "gif",
  // Снимки айфона, если браузер не пережал их в JPEG (lib/prepare-image.ts).
  "image/heic": "heic",
  "image/heif": "heif",
};

export const IMAGE_TYPE_ERROR = "Можно загружать только фотографии: JPEG, PNG, WebP, GIF или HEIC";

/** Расширение для файла этого типа, или null — такой файл не принимаем. */
export function imageExtension(type: string): string | null {
  return IMAGE_EXTENSIONS[type.toLowerCase()] ?? null;
}
