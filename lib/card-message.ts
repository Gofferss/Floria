/** Момент из фильма: получатель находит фильм и смотрит сцену с этой минуты. */
export type CardFilm = { on: boolean; title: string; time: string };

export const NO_FILM: CardFilm = { on: false, title: "", time: "" };

/**
 * Маска времени сцены: цифры сами раскладываются в «1:55:10» справа
 * налево, двоеточия ставить не нужно — на телефоне их искать неудобно.
 */
export function formatFilmTime(raw: string): string {
  const d = raw.replace(/\D/g, "").slice(0, 6);
  if (d.length <= 2) return d;
  if (d.length <= 4) return `${d.slice(0, -2)}:${d.slice(-2)}`;
  return `${d.slice(0, -4)}:${d.slice(-4, -2)}:${d.slice(-2)}`;
}

/** «55:10» или «1:55:10»; минуты и секунды — меньше 60. */
export function isValidFilmTime(time: string): boolean {
  return /^(\d{1,2}:[0-5]\d|[0-5]?\d):[0-5]\d$/.test(time.trim());
}

/** Строка для открытки: «Гордость и предубеждение» (1:55:10). Кавычки ставим сами. */
export function filmLine(film: CardFilm): string {
  if (!film.on) return "";
  const title = film.title.trim().replace(/^["'«„“]+|["'»“”]+$/g, "").trim();
  if (!title) return "";
  return film.time.trim() ? `«${title}» (${film.time.trim()})` : `«${title}»`;
}

/** То, что уйдёт в заказ и что флорист перепишет на карточку. */
export function composeCardText(message: string, film: CardFilm): string {
  return [message.trim(), filmLine(film)].filter(Boolean).join("\n");
}
