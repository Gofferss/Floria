// ================================================================
// Кто что видит в учёте.
//
// Себестоимость, средние цены, стоимость остатка и прибыль — только
// владельцам. Решение владельца от 21.10.2026.
//
// Владельческие роли — owner и admin: сейчас единственная учётная
// запись владельца заведена с ролью admin. Поэтому администратору
// магазина, если такой появится, нужно давать роль manager, а не admin —
// иначе он увидит себестоимость.
//
// Скрывается не вёрсткой, а данными: сервер просто не отдаёт эти поля
// тем, кому их видеть не положено.
// ================================================================

const OWNER_ROLES = new Set(["owner", "admin"]);

export function canSeeCosts(role: string | null | undefined): boolean {
  return !!role && OWNER_ROLES.has(role);
}

/** Начальный остаток вводится один раз, при запуске учёта, — только владельцем. */
export function canPostOpening(role: string | null | undefined): boolean {
  return canSeeCosts(role);
}
