/**
 * JSON.stringify не экранирует "<" — если в название/описание товара
 * попадёт буквально "</script>" (хоть сейчас поля редактирует только
 * персонал, не произвольный посетитель), это преждевременно закроет тег
 * и даст вставить в страницу что угодно после него. Экранированная
 * форма — валидный JSON-эскейп для "<": при разборе превращается
 * обратно в обычный символ, так что для самого JSON-LD ничего не меняется.
 */
export function safeJsonLd(data: unknown): string {
  return JSON.stringify(data).replace(/</g, "\\u003c");
}
